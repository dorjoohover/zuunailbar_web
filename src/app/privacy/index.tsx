function PolicySection({ section, index }: { section: any; index: number }) {
  return (
    <div className="p-6 sm:p-8 border-b border-gray-100">
      {/* TITLE */}
      <h2 className="text-xl font-bold text-gray-900 mb-4">
        {index + 1}. {section.title}
      </h2>

      {/* DESC */}
      {section.desc && (
        <p className="text-gray-600 whitespace-pre-line mb-6">{section.desc}</p>
      )}

      {/* ITEMS */}
      {section.items && (
        <ul className="space-y-4">
          {section.items.map((item: any, i: number) => (
            <li
              key={item.title}
              className="flex gap-4 items-start p-4 rounded-2xl border border-gray-200 bg-white shadow-sm"
            >
              {/* Number */}
              <div className="min-w-[48px] h-[48px] flex items-center justify-center rounded-xl bg-gray-100 font-bold">
                {index + 1}.{i + 1}
              </div>

              {/* Content */}
              <div className="flex flex-col gap-2 w-full">
                {/* TITLE */}
               

                {/* 🔥 CONTACT STYLE (email / website) */}
                {section.type === "contact" ? (
                  <>
                    <span className="text-sm text-gray-500">{item.label}</span>

                    {item.label === "И-мэйл" ? (
                      <a
                        href={`mailto:${item.value}`}
                        className="text-blue-600 font-semibold hover:underline"
                      >
                        {item.value}
                      </a>
                    ) : item.label === "Вэбсайт" ? (
                      <a
                        href={`https://${item.value}`}
                        target="_blank"
                        className="text-blue-600 font-semibold hover:underline"
                      >
                        {item.value}
                      </a>
                    ) : (
                      <span className="font-semibold text-gray-900">
                        {item.value}
                      </span>
                    )}
                  </>
                ) : (
                  <>
                    {/* NORMAL TYPE */}
                   <span className="font-semibold text-gray-900">
                  {item.title}
                </span>

                {/* DESC */}
                {item.desc && (
                  <span className="text-gray-600 whitespace-pre-line">
                    {item.desc}
                  </span>
                )}
                {item.description && (
                  <span className="text-gray-600 whitespace-pre-line">
                    {item.description}
                  </span>
                )}
                  </>
                )}

                {/* 🔥 SUB ITEMS */}
                {item.subItems && (
                  <ul className="list-disc pl-5 space-y-1 text-gray-600">
                    {item.subItems.map((sub: string, idx: number) => (
                      <li key={idx}>{sub}</li>
                    ))}
                  </ul>
                )}
              </div>
            </li>
          ))}
        </ul>
      )}

      {/* 🔥 NOTE (section level) */}
      {section.note && (
        <div className="mt-6 p-4 rounded-xl bg-gray-50 text-gray-600 text-sm">
          {section.note}
        </div>
      )}
    </div>
  );
}
